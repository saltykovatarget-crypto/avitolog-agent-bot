function getContextCases(count = 3) {
  const shuffled = [...CASES].filter(c => c.leads).sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map(c => {
    const loc = [c.niche, c.city, c.region, c.brand ? `(${c.brand})` : ""].filter(Boolean).join(", ");
    let res = `${c.leads} заявок по ${c.price} ₽`;
    if (c.days) res += ` за ${c.days} дней`;
    if (c.detail) res += `. ${c.detail}`;
    return `— ${loc}: ${res}`;
  }).join("\n");
}

